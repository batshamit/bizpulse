"""Recommendation Chat Agent — allows deep exploration of specific advice."""

from __future__ import annotations

from bizpulse.agents.runner import AgentRunner
from bizpulse.models.strategy import MarketingStrategy


async def chat_about_recommendation(
    runner: AgentRunner,
    strategy: MarketingStrategy,
    recommendation_index: int,
    user_message: str,
) -> str:
    """Explains or refines a specific recommendation based on user query."""
    if (
        not strategy.recommendations
        or recommendation_index < 0
        or recommendation_index >= len(strategy.recommendations)
    ):
        return "Invalid recommendation index."

    rec = strategy.recommendations[recommendation_index]

    system = (
        "You are the BizPulse Marketing Implementation Assistant. "
        "A user is asking for more detail about a specific recommendation "
        "generated by our Council of LLMs.\n\n"
        "CONTEXT:\n"
        f"Business Industry: {strategy.industry}\n"
        f"Overall Strategy Summary: {strategy.summary}\n\n"
        "THE SPECIFIC RECOMMENDATION UNDER DISCUSSION:\n"
        f"Channel: {rec.channel}\n"
        f"Action: {rec.action}\n"
        f"Rationale: {rec.rationale}\n"
        f"Priority: {rec.priority}\n\n"
        "GOAL:\n"
        "Provide a helpful, actionable, and detailed explanation or implementation "
        "plan for this specific recommendation. If the user asks for alternatives, "
        "provide them. Cite evidence from the original context if possible (though "
        "you only see the strategy here, you can infer from the rationale).\n\n"
        "Keep the tone professional, encouraging, and highly specific to this "
        "business's context."
    )

    user = f"User Question: {user_message}"

    # Use the judge for chat — usually the strongest model.
    cr = await runner.council.judge.complete(
        system=system,
        user=user,
        max_tokens=1024,
        temperature=0.7,
    )
    return cr.text
